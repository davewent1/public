// ---------------------------------------------------------------------------
// Front-end FAQ schema output
// ---------------------------------------------------------------------------
// When a post generated by this plugin is viewed on the front end, output the
// saved JSON-LD FAQ schema in <head>. The schema is stored as post meta so
// it never gets stripped by wp_kses_post during post saving.
add_action( 'wp_head', 'sbg_output_faq_schema' );

/**
 * Outputs the FAQ JSON-LD schema block for generated posts.
 *
 * Runs on wp_head. Exits silently if the current page is not a singular post
 * or if no FAQ schema meta was saved during generation.
 */
function sbg_output_faq_schema(): void {
	if ( ! is_singular( 'post' ) ) {
		return;
	}

	$post_id = (int) get_the_ID();
	$schema  = get_post_meta( $post_id, '_sbg_faq_schema', true );

	if ( empty( $schema ) ) {
		return;
	}

	// The schema is already a validated JSON string (encoded by wp_json_encode).
	// Output inside a standard JSON-LD script tag.
	echo '<script type="application/ld+json">' . "\n";
	// phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- JSON-LD does not need HTML escaping; escaping would break the schema.
	echo $schema . "\n";
	echo '</script>' . "\n";
}

