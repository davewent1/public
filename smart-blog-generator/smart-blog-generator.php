/**
 * Instantiates the admin controller, which registers all admin hooks.
 * The controller is only created on admin requests (see the is_admin() guard
 * in the require_once block above).
 */
function sbg_init(): void {
	if ( is_admin() ) {
		SBG_Admin_Controller::instance();
	}
}

